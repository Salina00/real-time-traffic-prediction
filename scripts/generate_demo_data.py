"""
Synthetic Demo Traffic Dataset Generator with Realistic Autoregressive Traffic Dynamics.

IMPORTANT DISCLAIMER:
The records generated by this script are realistic synthetic data created for
development, pipeline testing, and model demonstration when live TomTom API
observations or physical IoT sensor streams are unavailable.
All records are explicitly labelled with:
    data_source: "synthetic_demo"
Do NOT describe or present these records as genuine TomTom API observations.
"""

import argparse
import random
import logging
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import List, Dict, Any

import pandas as pd
import numpy as np

# Add project root to sys.path
import sys
BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))

from config.settings import PUNE_ROAD_POINTS, DEMO_DATA_DIR
from src.data_utils import clean_and_prepare_dataset

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)


def generate_synthetic_history(
    days: int = 3,
    interval_minutes: int = 5,
    seed: int = 42,
    road_points: List[Dict[str, Any]] = None
) -> pd.DataFrame:
    """
    Generates a continuous sequence of 5-minute traffic observations across
    the configured Pune road points using realistic autoregressive traffic flow.
    """
    random.seed(seed)
    np.random.seed(seed)

    points = road_points or PUNE_ROAD_POINTS
    now_utc = datetime.now(timezone.utc)
    start_utc = now_utc - timedelta(days=days)

    total_intervals = int((days * 24 * 60) / interval_minutes)
    logger.info(
        "Generating synthetic traffic dataset: %d days, %d-min interval (%d snapshots per road across %d roads)",
        days, interval_minutes, total_intervals, len(points)
    )

    records: List[Dict[str, Any]] = []

    # Generate smooth continuous time series for each road corridor
    for pt in points:
        road_id = pt["road_id"]
        base_free = float(pt.get("typical_free_flow_speed", 50.0))
        is_busy_corridor = road_id in ["swargate", "hinjawadi", "pune_central", "hadapsar", "shivajinagar", "viman_nagar"]

        # Corridor congestion depth during peak rush
        peak_drop = 0.62 if is_busy_corridor else 0.44

        # Initialize smooth baseline speed ratio
        curr_ratio = 0.90

        for i in range(total_intervals):
            current_time = start_utc + timedelta(minutes=i * interval_minutes)
            timestamp_str = current_time.isoformat()

            # Local IST hour = UTC + 5.5 hours
            utc_hour = current_time.hour + (current_time.minute / 60.0)
            ist_hour = (utc_hour + 5.5) % 24

            # Diurnal bell curves:
            # Morning peak (8:30 - 11:30 AM IST, center ~9:30 AM)
            # Evening peak (17:30 - 21:00 PM IST, center ~18:45 PM)
            m_bell = np.exp(-((ist_hour - 9.5) ** 2) / 2.8)
            e_bell = np.exp(-((ist_hour - 18.75) ** 2) / 3.2)
            rush_factor = float(np.clip(m_bell * 1.1 + e_bell * 1.05, 0.0, 1.0))

            target_ratio = 0.92 - (peak_drop * rush_factor)

            # Autoregressive smoothing (88% persistence from prior 5-minute state)
            curr_ratio = 0.88 * curr_ratio + 0.12 * target_ratio + np.random.normal(0, 0.012)
            curr_ratio = float(np.clip(curr_ratio, 0.22, 0.98))

            # Free-flow baseline speed with slight long-term variance
            free_flow_speed = round(base_free + np.sin(i / 100.0) * 1.5, 1)
            current_speed = round(max(5.0, free_flow_speed * curr_ratio), 1)

            # Simulated rare acute road closures (~1% occurrence, lasting 20-30m)
            # For demonstration, simulate isolated incidents on select corridors
            is_closed = (i in [140, 141, 142, 143, 520, 521, 522]) and road_id in ["swargate", "pune_central"]
            if is_closed:
                current_speed = round(max(3.0, free_flow_speed * 0.12), 1)

            confidence = round(float(np.clip(0.85 + np.random.normal(0, 0.04), 0.70, 1.0)), 2)

            # Travel times calculation
            distance_km = round(free_flow_speed / 30.0, 2)
            free_travel_time = int((distance_km / max(free_flow_speed, 1.0)) * 3600)
            cur_travel_time = int((distance_km / max(current_speed, 1.0)) * 3600)

            rec = {
                "timestamp": timestamp_str,
                "road_id": road_id,
                "road_name": pt.get("name", road_id),
                "latitude": pt["latitude"],
                "longitude": pt["longitude"],
                "frc": "FRC1",
                "current_speed": current_speed,
                "free_flow_speed": free_flow_speed,
                "current_travel_time": cur_travel_time,
                "free_flow_travel_time": free_travel_time,
                "confidence": confidence,
                "road_closure": is_closed,
                "data_source": "synthetic_demo"
            }
            records.append(rec)

    raw_df = pd.DataFrame(records)
    logger.info("Generated %d raw records. Performing cleaning and validation...", len(raw_df))

    # Clean and validate using data_utils
    output_path = DEMO_DATA_DIR / "pune_traffic_historical_demo.csv"
    cleaned_df = clean_and_prepare_dataset(raw_df, output_filepath=output_path)

    # Also save as parquet for fast loading
    parquet_path = DEMO_DATA_DIR / "pune_traffic_historical_demo.parquet"
    cleaned_df.to_parquet(parquet_path, index=False)

    logger.info("Successfully generated and saved demo dataset:")
    logger.info("  CSV:     %s", output_path)
    logger.info("  Parquet: %s", parquet_path)
    logger.info("  Total valid records: %d", len(cleaned_df))
    logger.info("  Congestion breakdown:\n%s", cleaned_df["congestion_level"].value_counts())

    return cleaned_df


def main():
    parser = argparse.ArgumentParser(description="Generate synthetic Pune traffic dataset for demonstration.")
    parser.add_argument("--days", type=int, default=3, help="Number of historical days to generate (default: 3)")
    parser.add_argument("--interval", type=int, default=5, help="Observation interval in minutes (default: 5)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility (default: 42)")
    args = parser.parse_args()

    generate_synthetic_history(days=args.days, interval_minutes=args.interval, seed=args.seed)


if __name__ == "__main__":
    main()
